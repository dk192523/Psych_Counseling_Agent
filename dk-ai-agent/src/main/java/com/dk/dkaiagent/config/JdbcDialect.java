package com.dk.dkaiagent.config;

/** Explicit SQL boundary: PostgreSQL compatibility mode does not make H2 PostgreSQL. */
public enum JdbcDialect {
    POSTGRESQL, H2;

    public boolean isH2() { return this == H2; }

    public String schema(String sql) {
        return isH2() ? sql.replace("TIMESTAMPTZ", "TIMESTAMP WITH TIME ZONE")
                .replace("BIGSERIAL", "BIGINT GENERATED BY DEFAULT AS IDENTITY") : sql;
    }

    public String choose(String postgres, String h2) { return isH2() ? h2 : postgres; }

    public String agoMillis() {
        return choose("CURRENT_TIMESTAMP - CAST(? AS DOUBLE PRECISION) * INTERVAL '1 millisecond'",
                "DATEADD('MILLISECOND', -CAST(? AS BIGINT), CURRENT_TIMESTAMP)");
    }

    public String agoDays() {
        return choose("CURRENT_TIMESTAMP - CAST(? AS DOUBLE PRECISION) * INTERVAL '1 day'",
                "DATEADD('DAY', -CAST(? AS INTEGER), CURRENT_TIMESTAMP)");
    }

    public String staleTurnCutoff() {
        return choose("CURRENT_TIMESTAMP - INTERVAL '5 minutes'", "DATEADD('MINUTE', -5, CURRENT_TIMESTAMP)");
    }

    public String previousTurnHours() {
        return choose("EXTRACT(EPOCH FROM (CURRENT_TIMESTAMP - created_at)) / 3600.0",
                "DATEDIFF('MILLISECOND', created_at, CURRENT_TIMESTAMP) / 3600000.0");
    }

    public String tombstoneUpsert() {
        return choose("""
                INSERT INTO psych_conversation_tombstone (conversation_id, owner_id)
                VALUES (?, ?)
                ON CONFLICT (conversation_id) DO UPDATE SET deleted_at = CURRENT_TIMESTAMP
                """, """
                MERGE INTO psych_conversation_tombstone t
                USING (VALUES (CAST(? AS VARCHAR(64)), CAST(? AS BIGINT))) s(conversation_id, owner_id)
                ON t.conversation_id = s.conversation_id
                WHEN MATCHED THEN UPDATE SET deleted_at = CURRENT_TIMESTAMP
                WHEN NOT MATCHED THEN INSERT (conversation_id, owner_id) VALUES (s.conversation_id, s.owner_id)
                """);
    }

    public String tombstoneInsert() {
        return choose("""
                INSERT INTO psych_conversation_tombstone (conversation_id, owner_id)
                VALUES (?, ?) ON CONFLICT (conversation_id) DO NOTHING
                """, """
                MERGE INTO psych_conversation_tombstone t
                USING (VALUES (CAST(? AS VARCHAR(64)), CAST(? AS BIGINT))) s(conversation_id, owner_id)
                ON t.conversation_id = s.conversation_id
                WHEN NOT MATCHED THEN INSERT (conversation_id, owner_id) VALUES (s.conversation_id, s.owner_id)
                """);
    }

    public String userDeletionTombstones() {
        return choose("""
                INSERT INTO psych_conversation_tombstone (conversation_id, owner_id)
                SELECT id, owner_id FROM psych_conversation WHERE owner_id = ?
                ON CONFLICT (conversation_id) DO UPDATE SET deleted_at = CURRENT_TIMESTAMP
                """, """
                MERGE INTO psych_conversation_tombstone t
                USING (SELECT id, owner_id FROM psych_conversation WHERE owner_id = ?) s
                ON t.conversation_id = s.id
                WHEN MATCHED THEN UPDATE SET deleted_at = CURRENT_TIMESTAMP
                WHEN NOT MATCHED THEN INSERT (conversation_id, owner_id) VALUES (s.id, s.owner_id)
                """);
    }

    public String conversationBootstrap() {
        return choose("""
                INSERT INTO psych_conversation (id, title, owner_id, created_at, updated_at)
                SELECT ?, ?, ?, CURRENT_TIMESTAMP, CURRENT_TIMESTAMP
                WHERE NOT EXISTS (
                    SELECT 1 FROM psych_conversation_tombstone t WHERE t.conversation_id = ?
                )
                ON CONFLICT (id) DO NOTHING
                """, """
                MERGE INTO psych_conversation c
                USING (SELECT CAST(? AS VARCHAR(64)) AS id, CAST(? AS VARCHAR(120)) AS title,
                              CAST(? AS BIGINT) AS owner_id
                       WHERE NOT EXISTS (SELECT 1 FROM psych_conversation_tombstone t WHERE t.conversation_id = ?)) s
                ON c.id = s.id
                WHEN NOT MATCHED THEN INSERT (id, title, owner_id, created_at, updated_at)
                    VALUES (s.id, s.title, s.owner_id, CURRENT_TIMESTAMP, CURRENT_TIMESTAMP)
                """);
    }

    public String userMessageInsert() {
        return choose("""
                INSERT INTO psych_chat_message (conversation_id, role, content, client_msg_id, created_at)
                VALUES (?, ?, ?, ?, CURRENT_TIMESTAMP)
                ON CONFLICT (conversation_id, client_msg_id) DO NOTHING
                """, """
                MERGE INTO psych_chat_message m
                USING (VALUES (CAST(? AS VARCHAR(64)), CAST(? AS VARCHAR(16)),
                               CAST(? AS VARCHAR), CAST(? AS VARCHAR(64)))) s(conversation_id, role, content, client_msg_id)
                ON m.conversation_id = s.conversation_id AND m.client_msg_id = s.client_msg_id
                WHEN NOT MATCHED THEN INSERT (conversation_id, role, content, client_msg_id, created_at)
                    VALUES (s.conversation_id, s.role, s.content, s.client_msg_id, CURRENT_TIMESTAMP)
                """);
    }

    public String memoryUpsert() {
        return choose("""
                INSERT INTO psych_conversation_memory (
                    conversation_id, digest, covered_until_message_id, covered_message_count, digest_chars, updated_at
                )
                VALUES (?, ?, ?, ?, ?, CURRENT_TIMESTAMP)
                ON CONFLICT (conversation_id) DO UPDATE SET
                    digest = EXCLUDED.digest,
                    covered_until_message_id = EXCLUDED.covered_until_message_id,
                    covered_message_count = EXCLUDED.covered_message_count,
                    digest_chars = EXCLUDED.digest_chars,
                    updated_at = CURRENT_TIMESTAMP
                WHERE psych_conversation_memory.covered_until_message_id < EXCLUDED.covered_until_message_id
                """, """
                MERGE INTO psych_conversation_memory m
                USING (VALUES (CAST(? AS VARCHAR(64)), CAST(? AS VARCHAR), CAST(? AS BIGINT),
                               CAST(? AS INTEGER), CAST(? AS INTEGER)))
                    s(conversation_id, digest, covered_until_message_id, covered_message_count, digest_chars)
                ON m.conversation_id = s.conversation_id
                WHEN MATCHED AND m.covered_until_message_id < s.covered_until_message_id THEN UPDATE SET
                    digest = s.digest, covered_until_message_id = s.covered_until_message_id,
                    covered_message_count = s.covered_message_count, digest_chars = s.digest_chars,
                    updated_at = CURRENT_TIMESTAMP
                WHEN NOT MATCHED THEN INSERT
                    (conversation_id, digest, covered_until_message_id, covered_message_count, digest_chars, updated_at)
                    VALUES (s.conversation_id, s.digest, s.covered_until_message_id, s.covered_message_count,
                            s.digest_chars, CURRENT_TIMESTAMP)
                """);
    }

    public String turnReservation() {
        return choose("""
                INSERT INTO psych_chat_turn(conversation_id, client_msg_id, request_hash, status)
                VALUES (?, ?, ?, 'RUNNING')
                ON CONFLICT(conversation_id, client_msg_id) DO UPDATE SET status = 'RUNNING', updated_at = CURRENT_TIMESTAMP
                """, """
                MERGE INTO psych_chat_turn t
                USING (VALUES (CAST(? AS VARCHAR(64)), CAST(? AS VARCHAR(64)), CAST(? AS VARCHAR(64))))
                    s(conversation_id, client_msg_id, request_hash)
                ON t.conversation_id = s.conversation_id AND t.client_msg_id = s.client_msg_id
                WHEN MATCHED THEN UPDATE SET status = 'RUNNING', updated_at = CURRENT_TIMESTAMP
                WHEN NOT MATCHED THEN INSERT (conversation_id, client_msg_id, request_hash, status)
                    VALUES (s.conversation_id, s.client_msg_id, s.request_hash, 'RUNNING')
                """);
    }
}
