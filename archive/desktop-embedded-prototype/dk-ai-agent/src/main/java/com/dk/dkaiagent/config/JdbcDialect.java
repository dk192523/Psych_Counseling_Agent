package com.dk.dkaiagent.config;

/** Small explicit dialect boundary; H2's PostgreSQL mode does not implement PostgreSQL. */
public enum JdbcDialect {
    POSTGRESQL,
    H2;

    public boolean isH2() {
        return this == H2;
    }

    public static String schema(String sql, boolean h2) {
        return h2 ? sql.replace("TIMESTAMPTZ", "TIMESTAMP WITH TIME ZONE")
                .replace("BIGSERIAL", "BIGINT GENERATED BY DEFAULT AS IDENTITY") : sql;
    }
}
